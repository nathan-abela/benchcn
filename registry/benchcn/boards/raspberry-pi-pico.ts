import type { BoardDefinition, PinDefinition } from "@/registry/benchcn/boards/types";

type PicoBus = {
  i2c?: [number, "sda" | "scl"];
  spi?: [number, "RX" | "CSn" | "SCK" | "TX"];
  uart?: [number, "TX" | "RX"];
};

const SPI_ROLE = { RX: "miso", CSn: "cs", SCK: "sclk", TX: "mosi" } as const;

// Function labels read exactly as Figure 2 of the datasheet prints them, in its left-to-right
// order; SPI RX/TX are mapped to miso/mosi for conflict detection.
function gp(number: number, gpio: number, bus: PicoBus, adc?: number): PinDefinition {
  const functions: string[] = [];
  const alt: NonNullable<PinDefinition["alt"]> = [];
  if (bus.uart) {
    functions.push(`UART${bus.uart[0]} ${bus.uart[1]}`);
    alt.push({ uart: { port: bus.uart[0], role: bus.uart[1] === "TX" ? "tx" : "rx" } });
  }
  if (bus.i2c) {
    functions.push(`I2C${bus.i2c[0]} ${bus.i2c[1].toUpperCase()}`);
    alt.push({ i2c: { bus: bus.i2c[0], role: bus.i2c[1] } });
  }
  if (bus.spi) {
    functions.push(`SPI${bus.spi[0]} ${bus.spi[1]}`);
    alt.push({ spi: { bus: bus.spi[0], role: SPI_ROLE[bus.spi[1]] } });
  }
  if (adc !== undefined) {
    functions.push(`ADC${adc}`);
    alt.push({ adc: { channel: adc } });
  }
  return { number, name: `GP${gpio}`, kind: "gpio", functions, alt };
}

