import type { WireChannelInfo } from "@/registry/benchcn/lib/wire";

import { siteConfig } from "../../../config/site";
import { boundIds, CATALOG } from "./catalog";
import { generateDashboard, installCommand } from "./codegen";
import { DEFAULT_WEBSOCKET_URL, type StudioState, type Widget } from "./model";

function describeChannel(channel: WireChannelInfo): string {
  const parts: string[] = [channel.kind ?? "sensor"];
  if (channel.u) parts.push(channel.u);
  if (channel.min !== undefined && channel.max !== undefined) {
    parts.push(`${channel.min} to ${channel.max}`);
  }
  const label = channel.label ? ` "${channel.label}"` : "";
  return `- ${channel.id}${label}: ${parts.join(", ")}`;
}

function describeWidget(widget: Widget): string {
  const entry = CATALOG[widget.type];
  const { label, title } = widget.props;
  const name = typeof label === "string" ? label : typeof title === "string" ? title : "";
  const bindings = entry.slots
    .map((slot) => {
      const ids = boundIds(widget, slot.name);
      return ids.length > 0 ? `${slot.label.toLowerCase()} ${ids.join(", ")}` : null;
    })
    .filter((text): text is string => text !== null);
  const named = name ? ` "${name}"` : "";
  const bound = bindings.length > 0 ? `, ${bindings.join("; ")}` : "";
  return `- ${entry.title}${named}, ${widget.span} of 12 columns${bound}`;
}

/**
 * A prompt for a coding agent: what to install, the layout in words, the device's channels and
 * the generated file to start from, so the agent adapts it to the project instead of guessing.
 */
export function buildStudioPrompt(
  state: StudioState,
  channels: readonly WireChannelInfo[],
): string {
  const { namespace, itemUrlTemplate } = siteConfig.registry;
  const { code, items } = generateDashboard(state);
  const source =
    state.source.kind === "mock"
      ? "useMockDevice() for now; switch to useWebSocketSource or useSerialSource when the hardware is ready."
      : `useWebSocketSource(${JSON.stringify(state.source.url || DEFAULT_WEBSOCKET_URL)}).`;
  const lines = [
    `Add this dashboard to the project using the ${namespace} shadcn/ui registry.`,
    "",
    `1. If components.json has no "${namespace}" entry under "registries", add: "${namespace}": "${itemUrlTemplate}"`,
    `2. Run: ${installCommand(items, "pnpm dlx", namespace)}`,
    `3. Read ${siteConfig.url}/llms.txt for the components, the source hooks and the wire protocol.`,
    `4. Data source: ${source}`,
    "5. Keep commanded and confirmed state separate for controls, and respect prefers-reduced-motion.",
    "",
    "Layout, a 12-column grid that stacks to one column on phones, in this order:",
    ...(state.widgets.length > 0 ? state.widgets.map(describeWidget) : ["- (empty)"]),
  ];
  if (channels.length > 0) {
    lines.push("", "Channels the device reports:", ...channels.map(describeChannel));
  }
  lines.push(
    "",
    "Start from this file, generated by the benchcn Studio, and fit it to the project:",
    "",
    "```tsx",
    code.trimEnd(),
    "```",
  );
  return lines.join("\n");
}
